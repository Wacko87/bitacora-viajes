const EURO_COUNTRIES = new Set([
  'ES', 'FR', 'IT', 'DE', 'PT', 'NL', 'BE', 'AT', 'GR', 'IE', 'FI', 'SK', 'SI', 'EE', 'LV', 'LT', 'CY', 'MT', 'LU', 'HR'
]);

/**
 * Obtiene la serie completa de monedas y billetes oficiales en circulación para el país y año del viaje.
 */
export function getCirculatingCurrenciesForTrip(countryCode: string, tripYear?: number): CirculatingPiece[] {
  const code = (countryCode || 'ES').toUpperCase();

  // 1. Egipto
  if (code === 'EG') {
    return DETAILED_SERIES.EG;
  }

  // 2. Países de la Eurozona (desde 2002)
  if (EURO_COUNTRIES.has(code) && (!tripYear || tripYear >= 2002)) {
    const euroCountry = PRESEEDED_CURRENCIES[code]?.countryName || code;
    return DETAILED_SERIES.EUR_SERIES.map((p) => ({
      ...p,
      countryCode: code,
      name: p.name.replace('de cada país', `de ${euroCountry}`),
    }));
  }

  // 3. Destinos detallados preconfigurados (UK, US, JP, PL, etc.)
  if (code === 'PL') {
    const plSeries = DETAILED_SERIES.PL;
    if (tripYear && tripYear < 2017) {
      return plSeries.filter((p) => p.denomination !== '500');
    }
    return plSeries;
  }

  if (DETAILED_SERIES[code]) {
    return DETAILED_SERIES[code];
  }

  // 4. Generador dinámico universal para cualquier otro país del mundo
  const config = getCurrencyForCountry(code);
  const pieces: CirculatingPiece[] = [];

  // Monedas
  config.coins.forEach((coinVal) => {
    pieces.push({
      id: `${code}-coin-${coinVal}`,
      countryCode: code,
      category: 'coin',
      denomination: coinVal,
      displayValue: `${coinVal} ${config.symbol || config.currencyCode}`,
      currencyCode: config.currencyCode,
      currencySymbol: config.symbol,
      name: `Moneda de ${coinVal} ${config.currencyName}`,
      motif: `Emblema oficial de ${config.countryName}`,
      material: 'Moneda metálica en curso legal',
      badgeColor: '#f59e0b',
    });
  });

  // Billetes
  config.banknotes.forEach((noteVal) => {
    pieces.push({
      id: `${code}-note-${noteVal}`,
      countryCode: code,
      category: 'banknote',
      denomination: noteVal,
      displayValue: `${noteVal} ${config.symbol || config.currencyCode}`,
      currencyCode: config.currencyCode,
      currencySymbol: config.symbol,
      name: `Billete de ${noteVal} ${config.currencyName}`,
      motif: `Iconografía nacional de ${config.countryName}`,
      material: 'Papel moneda o polímero de seguridad',
      gradient: 'from-amber-950/60 to-zinc-900',
      badgeColor: '#10b981',
    });
  });

  return pieces;
}

/**
 * Normaliza y compara si una denominación de recuerdo (artifact) coincide
 * con una pieza de la serie en circulación (piece).
 *
 * REGLA CRÍTICA: Las denominaciones numéricas NUNCA deben coincidir como subcadenas.
 * Ejemplo: "20" NO debe coincidir con "200", ni "10" con "100", ni "1" con "10".
 */
export function matchesDenomination(artifactDenom?: string | null, pieceDenom?: string): boolean {
  if (!artifactDenom || !pieceDenom) return false;

  const trimA = artifactDenom.trim().toLowerCase();
  const trimP = pieceDenom.trim().toLowerCase();

  // 1. Coincidencia exacta directa
  if (trimA === trimP) return true;

  // 2. Normalización alfanumérica sin espacios ni puntuación (ej: "50 p" vs "50p")
  const cleanA = trimA.replace(/[^a-z0-9]/g, '');
  const cleanP = trimP.replace(/[^a-z0-9]/g, '');
  if (cleanA === cleanP) return true;

  // 3. Extracción de tokens numéricos delimitados por palabras (\b)
  // Ej: "20 Złotych" -> 20; "Billete de 20" -> 20; "200" -> 200
  const matchA = trimA.match(/\b(\d+(?:[.,]\d+)?)\b/);
  const matchP = trimP.match(/\b(\d+(?:[.,]\d+)?)\b/);

  if (matchA && matchP) {
    const numA = parseFloat(matchA[1].replace(',', '.'));
    const numP = parseFloat(matchP[1].replace(',', '.'));

    // Deben ser exactamente el mismo valor numérico
    if (!isNaN(numA) && !isNaN(numP) && numA === numP) {
      // Diferenciar unidades fraccionarias (ej: 50 céntimos / piastras / groszy vs 50 libras / zloty)
      const subunitKeywords = /cent|cts|ct|c\b|p\b|piastr|grosz|gr\b|ø|sen\b/i;
      const isSubunitA = subunitKeywords.test(trimA);
      const isSubunitP = subunitKeywords.test(trimP);

      return isSubunitA === isSubunitP;
    }
  }

  return false;
}
